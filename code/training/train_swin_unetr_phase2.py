"""
train_swin_unetr_phase2.py

Phase 2: Swin-UNETR Student Distillation with Pseudo-Ground Truth Consensus Masks.

Uses the CLEAN_HIGH_CONFIDENCE and WEAK_COARSE consensus masks generated by the
multi-model ensemble evaluation pipeline as pseudo-ground truth labels.

Key features:
  - Reads ensemble_audit_summary.csv to select CLEAN_HIGH_CONFIDENCE cases
    and WEAK_COARSE cases with hard-threshold autolabels (ignore_index=255)
  - Uses AsymmetricPDCELoss / DiceCE with ignore_index=255 boundary support
  - 4-fold cross-validation aligned identically to train_mednext_phase2.py (seed=42)
  - Optional Phase 1 pretrained checkpoint loading (warm-start finetuning)
  - MONAI SwinUNETR backbone (img_size=(96,96,96), feature_size=48, use_checkpoint=True)
  - Saves best + last checkpoint every epoch
"""

