def main():
    parser = argparse.ArgumentParser(description="Phase 2 Swin-UNETR Distillation Training")
    parser.add_argument("--data_dir", type=str, required=True,
                        help="Root dir containing <subject_id>/ct.nii.gz")
    parser.add_argument("--audit_csv", type=str, required=True,
                        help="Path to ensemble_audit_summary.csv")
    parser.add_argument("--ensemble_out_dir", type=str, required=True,
                        help="Dir containing <subject_id>_consensus.nii.gz")
    parser.add_argument("--autolabel_dir", type=str, default=None,
                        help="Dir containing <subject_id>_autolabel.nii.gz")
    parser.add_argument("--gold_standard_dir", type=str, default=None)
    parser.add_argument("--out_dir", type=str, default="results/swin_unetr_phase2")
    parser.add_argument("--fold", type=int, default=0, help="Fold index (0..num_folds-1)")
    parser.add_argument("--num_folds", type=int, default=4)
    parser.add_argument("--epochs", type=int, default=150)
    parser.add_argument("--batch_size", type=int, default=1)
    parser.add_argument("--lr", type=float, default=1e-4)
    parser.add_argument("--val_interval", type=int, default=5)
    parser.add_argument("--use_weak", action="store_true", default=False)
    parser.add_argument("--pretrained_ckpt", type=str, default=None)
    parser.add_argument("--max_cases", type=int, default=0)
    parser.add_argument("--seed", type=int, default=42)
    args = parser.parse_args()

    os.makedirs(args.out_dir, exist_ok=True)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print(f"[Phase 2 Swin-UNETR] Device: {device} | Fold: {args.fold}/{args.num_folds} | use_weak: {args.use_weak}")

    data_pairs = discover_phase2_dataset(
        data_dir=args.data_dir,
        audit_csv=args.audit_csv,
        ensemble_out_dir=args.ensemble_out_dir,
        autolabel_dir=args.autolabel_dir,
        use_weak=args.use_weak,
        gold_standard_dir=args.gold_standard_dir,
        max_cases=args.max_cases,
        seed=args.seed,
    )

    np.random.seed(args.seed)
    indices = np.random.permutation(len(data_pairs))
    if args.fold >= 0:
        folds       = np.array_split(indices, args.num_folds)
        val_indices = folds[args.fold]
        train_idx   = np.setdiff1d(indices, val_indices)
        train_files = [data_pairs[i] for i in train_idx]
        val_files   = [data_pairs[i] for i in val_indices]
        print(f"[Fold {args.fold}/{args.num_folds}] Train: {len(train_files)} | Val: {len(val_files)}")
    else:
        split       = int(0.8 * len(data_pairs))
        train_files = [data_pairs[i] for i in indices[:split]]
        val_files   = [data_pairs[i] for i in indices[split:]]
        print(f"[80/20 Split] Train: {len(train_files)} | Val: {len(val_files)}")

    # Fast validation subsample (50 scans max) to keep epoch pace fast
    if len(val_files) > 50:
        val_files_eval = val_files[:50]
        print(f"  [Fast Val] Subsampled to {len(val_files_eval)} scans.")
    else:
        val_files_eval = val_files

    train_trans, val_trans = get_transforms(roi_size=(96, 96, 96))
    train_ds = Dataset(data=train_files, transform=train_trans)
    val_ds   = Dataset(data=val_files_eval, transform=val_trans)

    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True,
                              num_workers=4, pin_memory=True)
    val_loader   = DataLoader(val_ds, batch_size=1, shuffle=False,
                              num_workers=2, pin_memory=True)

    # Initialize Swin-UNETR
    model = SwinUNETR(
        in_channels=1,
        out_channels=NUM_CLASSES,
        feature_size=48,
        use_checkpoint=True,
        spatial_dims=3,
    ).to(device)

    # Loss selection
    if AsymmetricPDCELoss is not None:
        loss_function = AsymmetricPDCELoss(alpha=2.0, beta=1.0, ignore_index=IGNORE_INDEX)
        print("[Loss] AsymmetricPDCELoss(alpha=2.0, beta=1.0, ignore_index=255) active")
    else:
        loss_function = DiceCEWithIgnoreLoss(num_classes=NUM_CLASSES, ignore_index=IGNORE_INDEX)
        print("[Loss] DiceCEWithIgnoreLoss fallback active")

    optimizer = torch.optim.AdamW(model.parameters(), lr=args.lr, weight_decay=1e-5)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs, eta_min=1e-6)
    scaler = torch.amp.GradScaler('cuda')

    dice_metric = DiceMetric(include_background=False, reduction="mean")
    dice_metric_batch = DiceMetric(include_background=False, reduction="mean_batch")
    post_label = AsDiscrete(to_onehot=NUM_CLASSES)
    post_pred  = AsDiscrete(argmax=True, to_onehot=NUM_CLASSES)

    best_val_dice = 0.0
    start_epoch = 1

    # Checkpoint loading / warm-start
    last_ckpt_path = os.path.join(args.out_dir, "last_swin_unetr_phase2.pt")
    best_ckpt_path = os.path.join(args.out_dir, "best_swin_unetr_phase2.pt")

    if os.path.isfile(last_ckpt_path):
        print(f"Resuming from last checkpoint: {last_ckpt_path}")
        ckpt = torch.load(last_ckpt_path, map_location=device)
        model.load_state_dict(ckpt["model_state_dict"])
        if "optimizer_state_dict" in ckpt:
            optimizer.load_state_dict(ckpt["optimizer_state_dict"])
        if "scheduler_state_dict" in ckpt:
            scheduler.load_state_dict(ckpt["scheduler_state_dict"])
        start_epoch = ckpt.get("epoch", 0) + 1
        best_val_dice = ckpt.get("best_val_dice", 0.0)
        print(f"  Resumed at epoch {start_epoch}, best Dice: {best_val_dice:.4f}")
    elif args.pretrained_ckpt and os.path.isfile(args.pretrained_ckpt):
        print(f"Loading Phase 1 pretrained checkpoint: {args.pretrained_ckpt}")
        ckpt = torch.load(args.pretrained_ckpt, map_location=device)
        state_dict = ckpt["model_state_dict"] if (isinstance(ckpt, dict) and "model_state_dict" in ckpt) else ckpt
        # Filter matching keys
        model_dict = model.state_dict()
        matched = {k: v for k, v in state_dict.items() if k in model_dict and v.shape == model_dict[k].shape}
        model_dict.update(matched)
        model.load_state_dict(model_dict)
        print(f"  Loaded {len(matched)}/{len(model_dict)} layers from Phase 1.")

    print(f"\n[Phase 2 Swin-UNETR] Starting training loop (epochs {start_epoch} -> {args.epochs})...")

    for epoch in range(start_epoch, args.epochs + 1):
        model.train()
        epoch_loss = 0.0
        step = 0

        for batch_data in train_loader:
            step += 1
            inputs = batch_data["image"].to(device)
            labels = batch_data["label"].to(device)

            optimizer.zero_grad()
            with torch.amp.autocast('cuda'):
                outputs = model(inputs)
                loss = loss_function(outputs, labels)

            scaler.scale(loss).backward()
            scaler.unscale_(optimizer)
            torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
            scaler.step(optimizer)
            scaler.update()

            epoch_loss += loss.item()

        scheduler.step()
        epoch_loss /= max(step, 1)
        current_lr = scheduler.get_last_lr()[0]
        print(f"Epoch [{epoch:03d}/{args.epochs}] Loss: {epoch_loss:.4f}  LR: {current_lr:.2e}", flush=True)

        # Save last checkpoint every epoch
        torch.save({
            "epoch": epoch,
            "model_state_dict": model.state_dict(),
            "optimizer_state_dict": optimizer.state_dict(),
            "scheduler_state_dict": scheduler.state_dict(),
            "best_val_dice": best_val_dice,
            "epoch_loss": epoch_loss,
        }, last_ckpt_path)

        # Validation Step
        if epoch % args.val_interval == 0:
            model.eval()
            dice_metric.reset()
            dice_metric_batch.reset()
            with torch.no_grad():
                for val_data in val_loader:
                    val_inputs = val_data["image"].to(device)
                    val_labels = val_data["label"].to(device)
                    # Mask out 255 for validation metric calculation on both predictions and labels (F03/F15)
                    val_mask = (val_labels != IGNORE_INDEX)
                    val_labels_clean = torch.where(val_mask, val_labels, torch.zeros_like(val_labels))

                    with torch.amp.autocast('cuda'):
                        val_outputs = sliding_window_inference(
                            inputs=val_inputs,
                            roi_size=(96, 96, 96),
                            sw_batch_size=4,
                            predictor=model,
                            overlap=0.5,
                        )

                    val_outputs_list = [post_pred(i) for i in decollate_batch(val_outputs)]
                    val_labels_list  = [post_label(i) for i in decollate_batch(val_labels_clean)]
                    vmasks = [m for m in decollate_batch(val_mask)]
                    cleaned_preds = []
                    cleaned_labels = []
                    for p, l, m in zip(val_outputs_list, val_labels_list, vmasks):
                        if m.dim() < p.dim():
                            m = m.unsqueeze(0)
                        cleaned_preds.append(torch.where(m, p, torch.zeros_like(p)))
                        cleaned_labels.append(torch.where(m, l, torch.zeros_like(l)))
                    dice_metric(y_pred=cleaned_preds, y=cleaned_labels)
                    dice_metric_batch(y_pred=cleaned_preds, y=cleaned_labels)

            mean_dice = dice_metric.aggregate().item()
            organ_dices = dice_metric_batch.aggregate()
            dice_metric.reset()
            dice_metric_batch.reset()

            organ_strs = [f"{ORGAN_NAMES[i+1]}: {organ_dices[i].item():.4f}" for i in range(len(organ_dices))]
            print(f"  [Val Epoch {epoch:03d}] Mean Dice: {mean_dice:.4f} | " + " | ".join(organ_strs), flush=True)

            if mean_dice > best_val_dice:
                best_val_dice = mean_dice
                torch.save(model.state_dict(), best_ckpt_path)
                print(f"  [+] New Best Model Saved! Mean Dice: {best_val_dice:.4f} -> {best_ckpt_path}", flush=True)

    print(f"\nTraining Complete for Fold {args.fold}! Best Validation Dice: {best_val_dice:.4f}")


if __name__ == "__main__":
    main()
