# Dataset Discovery (Identical to train_mednext_phase2.py)
# ---------------------------------------------------------------------------

def discover_phase2_dataset(
    data_dir,
    audit_csv,
    ensemble_out_dir,
    autolabel_dir=None,
    use_weak=False,
    gold_standard_dir=None,
    max_cases=0,
    seed=42,
    require_foreground=True,
):
    """Build image/label pairs using ensemble consensus masks as labels."""
    if not os.path.exists(audit_csv):
        raise FileNotFoundError(f"Audit CSV not found: {audit_csv}")

    gold_standard_ids = set()
    if gold_standard_dir and os.path.exists(gold_standard_dir):
        import glob
        gs_files = glob.glob(os.path.join(gold_standard_dir, "*.nii.gz"))
        for gs_file in gs_files:
            subject_id = os.path.basename(gs_file).replace('.nii.gz', '')
            gold_standard_ids.add(subject_id)

    df = pd.read_csv(audit_csv)
    df = df[df['status'] == 'SUCCESS']

    categories = ['CLEAN_HIGH_CONFIDENCE']
    if use_weak:
        categories.append('WEAK_COARSE')

    selected = df[df['triage_category'].isin(categories)]
    print(f"[Phase 2 Dataset] Selected {len(selected):,} subjects:")
    for cat in categories:
        n = (selected['triage_category'] == cat).sum()
        print(f"  - {cat}: {n:,} cases")

    data_pairs = []
    missing_ct = 0
    missing_consensus = 0
    weak_using_autolabel = 0
    weak_fallback_to_consensus = 0

    for _, row in selected.iterrows():
        sub_id   = str(row['subject_id'])
        category = row['triage_category']

        ct_path        = os.path.join(data_dir, sub_id, "ct.nii.gz")
        consensus_path = os.path.join(ensemble_out_dir, f"{sub_id}_consensus.nii.gz")

        if not os.path.exists(ct_path):
            missing_ct += 1
            continue
        if not os.path.exists(consensus_path):
            missing_consensus += 1
            continue

        if category == 'WEAK_COARSE' and autolabel_dir:
            autolabel_path = os.path.join(autolabel_dir, f"{sub_id}_autolabel.nii.gz")
            if os.path.exists(autolabel_path):
                label_path = autolabel_path
                weak_using_autolabel += 1
            else:
                label_path = consensus_path
                weak_fallback_to_consensus += 1
        else:
            label_path = consensus_path

        # Verify valid 3D scan geometry and prevent scout/corrupt volumes from crashing DataLoader
        try:
            import nibabel as nib
            ct_hdr = nib.load(ct_path).header
            ct_shape = ct_hdr.get_data_shape()
            lbl_hdr = nib.load(label_path).header
            lbl_shape = lbl_hdr.get_data_shape()
        except Exception as e:
            print(f"  WARNING: Skipping {sub_id} due to corrupt NIfTI header: {e}")
            continue

        if len(ct_shape) != 3:
            print(f"  WARNING: Skipping {sub_id} because CT is not 3D (shape {ct_shape})")
            continue
        if len(lbl_shape) != 3:
            print(f"  WARNING: Skipping {sub_id} because label is not 3D (shape {lbl_shape})")
            continue
        if min(ct_shape) < 16 or min(lbl_shape) < 16:
            print(f"  WARNING: Skipping {sub_id} because scan is too small/scout (CT shape {ct_shape}, label shape {lbl_shape})")
            continue

        # Verify non-empty foreground GI supervision (prevent all-background masks from poisoning distillation)
        if require_foreground:
            # Fast-path check: if audit summary recorded zero Betti components across all GI organs, foreground is guaranteed empty
            betti_cols = [c for c in ['stomach_betti_consensus', 'duodenum_betti_consensus', 'small_bowel_betti_consensus', 'colon_betti_consensus'] if c in row]
            if betti_cols and sum(row[c] for c in betti_cols) == 0:
                print(f"  WARNING: Skipping {sub_id} because audit record indicates zero foreground GI components.")
                continue

            try:
                import numpy as np
                lbl_nii = nib.load(label_path)
                lbl_data = np.asanyarray(lbl_nii.dataobj)
                fg_voxels = int(np.sum((lbl_data >= 1) & (lbl_data <= 4)))
                if fg_voxels == 0:
                    print(f"  WARNING: Skipping {sub_id} because label contains zero foreground GI voxels (all background).")
                    continue
            except Exception as e:
                print(f"  WARNING: Skipping {sub_id} due to NIfTI read error checking foreground: {e}")
                continue

        is_gs = sub_id in gold_standard_ids
        data_pairs.append({
            "image": ct_path,
            "label": label_path,
            "subject_id": sub_id,
            "category": category,
            "is_gold_standard": is_gs,
        })

    print(f"  Missing CT: {missing_ct} | Missing Consensus: {missing_consensus}")
    if use_weak:
        print(f"  WEAK cases using autolabel (255 masking): {weak_using_autolabel}")
        if weak_fallback_to_consensus:
            print(f"  WARNING: {weak_fallback_to_consensus} WEAK cases fell back to consensus.")
    print(f"  Final usable pairs: {len(data_pairs):,}")

    if max_cases > 0 and len(data_pairs) > max_cases:
        gs_pairs = [p for p in data_pairs if p.get("is_gold_standard", False)]
        non_gs_pairs = [p for p in data_pairs if not p.get("is_gold_standard", False)]
        rng = _rnd.Random(seed)
        n_non_gs = max(0, max_cases - len(gs_pairs))
        sampled_non_gs = rng.sample(non_gs_pairs, min(n_non_gs, len(non_gs_pairs)))
        data_pairs = gs_pairs + sampled_non_gs
        print(f"  [Capped] Total {len(data_pairs)} cases (seed={seed}, max_cases={max_cases})")

    return data_pairs


