#!/usr/bin/env python3
"""
code/project10/evaluation/run_clinical_turing_test.py
===================================================
Project 10 Clinical Turing Test: Anatomical Downstream Invariance Audit.

Evaluates whether synthetic contrast-enhanced CT scans generated by Project 10
preserve the anatomical structure of the human gastrointestinal tract as measured
by the frozen Project 9 MedNeXt-B 5-organ segmentation model.

Computes:
  - Inter-phase Dice agreement: Dice(M_real, M_synth) across GI organs
  - Absolute ΔDice deviation: |Dice_real - Dice_synth|
  - Organ-specific preservation: Stomach, Duodenum, Small Bowel, Colon

Usage:
  python run_clinical_turing_test.py \
    --synthetic_dir results/project10/synthetic_volumes \
    --real_dir results/project10/registered_volumes \
    --model_path results/mednext_phase3/fold_2/best_mednext_phase2.pt \
    --out_csv results/project10/evaluation_reports/clinical_turing_test_summary.csv \
    --num_cases 50
"""

import argparse
import glob
import logging
import os
import sys
from pathlib import Path

import nibabel as nib
import numpy as np
import pandas as pd
import SimpleITK as sitk
import torch
import torch.nn.functional as F

BASE_DIR = Path(__file__).resolve().parents[3]
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from nnunet_mednext import create_mednext_v1
from monai.inferers import sliding_window_inference

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s",
    datefmt="%Y-%m-%d %H:%M:%S",
)
log = logging.getLogger("clinical_turing_test")

ORGAN_MAP = {
    1: "stomach",
    2: "duodenum",
    3: "small_bowel",
    4: "colon"
}


def compute_binary_dice(m1: np.ndarray, m2: np.ndarray) -> float:
    """Computes binary Dice coefficient between two masks."""
    b1 = (m1 > 0)
    b2 = (m2 > 0)
    denom = b1.sum() + b2.sum()
    if denom == 0:
        return 1.0  # Both empty -> perfect agreement
    inter = (b1 & b2).sum()
    return float(2.0 * inter / denom)


def run_model_inference(ct_vol: np.ndarray, model: torch.nn.Module, device: torch.device) -> np.ndarray:
    """Runs sliding window inference on CT volume (HU normalized to [0, 1])."""
    # Soft tissue abdominal window: [-175, 250] HU -> [0, 1]
    norm_vol = np.clip(ct_vol, -175.0, 250.0)
    norm_vol = (norm_vol - (-175.0)) / (250.0 - (-175.0))

    tensor = torch.from_numpy(norm_vol).float().unsqueeze(0).unsqueeze(0).to(device)

    with torch.no_grad():
        with torch.amp.autocast(device_type="cuda" if device.type == "cuda" else "cpu"):
            logits = sliding_window_inference(
                inputs=tensor,
                roi_size=(96, 96, 96),
                sw_batch_size=2,
                predictor=model,
                overlap=0.25,
                mode="gaussian",
            )
            pred = torch.argmax(logits, dim=1).squeeze(0).cpu().numpy().astype(np.uint8)

    return pred


def main():
    parser = argparse.ArgumentParser(description="Clinical Turing Test for Project 10")
    parser.add_argument("--synthetic_dir", type=str,
                        default="/mnt/scratch/user/chrsong/mp-factory/results/project10/synthetic_volumes",
                        help="Path to synthetic contrast volumes")
    parser.add_argument("--real_dir", type=str,
                        default="/mnt/scratch/user/chrsong/mp-factory/results/project10/registered_volumes",
                        help="Path to real registered volumes")
    parser.add_argument("--model_path", type=str,
                        default="/mnt/scratch/user/chrsong/mp-factory/results/mednext_phase3/fold_2/best_mednext_phase2.pt",
                        help="Path to frozen Project 9 MedNeXt model checkpoint")
    parser.add_argument("--out_csv", type=str,
                        default="/mnt/scratch/user/chrsong/mp-factory/results/project10/evaluation_reports/clinical_turing_test_summary.csv",
                        help="Output evaluation CSV")
    parser.add_argument("--num_cases", type=int, default=50,
                        help="Number of representative paired cases to test")
    parser.add_argument("--array_id", type=int, default=0,
                        help="Worker array index for sharding")
    parser.add_argument("--total_workers", type=int, default=1,
                        help="Total parallel workers")
    args = parser.parse_args()

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    log.info(f"Using compute device: {device}")

    # 1. Load frozen MedNeXt-B model
    log.info(f"Loading frozen Project 9 MedNeXt-B model from {args.model_path}")
    model = create_mednext_v1(
        num_classes=5,
        model_id="B",
        kernel_size=3,
        checkpoint_style=None
    ).to(device)

    ckpt = torch.load(args.model_path, map_location=device)
    if isinstance(ckpt, dict) and "model_state_dict" in ckpt:
        state_dict = ckpt["model_state_dict"]
    else:
        state_dict = ckpt

    clean_state_dict = {k.replace("module.", ""): v for k, v in state_dict.items()}
    model.load_state_dict(clean_state_dict)
    model.eval()
    log.info("Model loaded and set to evaluation mode.")

    # 2. Discover pairs
    all_synth_files = sorted(glob.glob(os.path.join(args.synthetic_dir, "*_synthetic_contrast.nii.gz")))
    log.info(f"Found {len(all_synth_files)} synthetic volumes in {args.synthetic_dir}")

    chunk_size = (len(all_synth_files) + args.total_workers - 1) // args.total_workers
    start_idx = args.array_id * chunk_size
    end_idx = min(start_idx + chunk_size, len(all_synth_files))
    synth_files = all_synth_files[start_idx:end_idx]
    log.info(f"[Worker {args.array_id}/{args.total_workers}] Assigned {len(synth_files)} volumes (indices {start_idx}..{end_idx-1})")

    records = []
    processed = 0

    for s_path in synth_files:
        stem = os.path.basename(s_path).replace("_synthetic_contrast.nii.gz", "")
        real_path = os.path.join(args.real_dir, f"{stem}_reg.nii.gz")

        if not os.path.isfile(real_path):
            continue

        try:
            s_nii = nib.load(s_path)
            r_nii = nib.load(real_path)

            s_arr = np.asanyarray(s_nii.dataobj).astype(np.float32)
            r_arr = np.asanyarray(r_nii.dataobj).astype(np.float32)

            if s_arr.shape != r_arr.shape:
                continue

            # Run MedNeXt segmentation on both real and synthetic contrast CTs
            pred_real = run_model_inference(r_arr, model, device)
            pred_synth = run_model_inference(s_arr, model, device)

            # Compute organ preservation metrics
            case_metrics = {
                "pair_id": stem,
                "shape_x": s_arr.shape[0],
                "shape_y": s_arr.shape[1],
                "shape_z": s_arr.shape[2],
            }

            organ_dices = []
            for org_id, org_name in ORGAN_MAP.items():
                m_real = (pred_real == org_id)
                m_synth = (pred_synth == org_id)
                d = compute_binary_dice(m_real, m_synth)
                case_metrics[f"turing_dice_{org_name}"] = round(d, 4)
                organ_dices.append(d)

            case_metrics["mean_turing_dice"] = round(float(np.mean(organ_dices)), 4)
            case_metrics["passed_turing_test"] = bool(case_metrics["mean_turing_dice"] >= 0.70)

            records.append(case_metrics)
            processed += 1
            log.info(f"[{processed}/{args.num_cases}] {stem} | Mean Turing Dice: {case_metrics['mean_turing_dice']:.4f}")

            if processed >= args.num_cases:
                break

        except Exception as e:
            log.warning(f"Error evaluating {stem}: {e}")

    if records:
        df = pd.DataFrame(records)
        os.makedirs(os.path.dirname(args.out_csv), exist_ok=True)
        df.to_csv(args.out_csv, index=False)
        log.info(f"Clinical Turing Test complete! Saved to {args.out_csv}")
        print("\n" + "=" * 60)
        print(" CLINICAL TURING TEST SUMMARY (REAL VS SYNTHETIC CONTRAST)")
        print("=" * 60)
        print(df[["turing_dice_stomach", "turing_dice_duodenum", "turing_dice_small_bowel", "turing_dice_colon", "mean_turing_dice"]].mean().to_string())
        print(f"Total Cases Passed: {df['passed_turing_test'].sum()} / {len(df)} ({df['passed_turing_test'].mean() * 100:.1f}%)")
    else:
        log.error("No valid pairs evaluated.")


if __name__ == "__main__":
    main()
