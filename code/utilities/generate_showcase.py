def process_subject(subject_id, data_dir, jhu_dir, out_base_dir, mask_dir=None):
    """
    Executes the full showcase pipeline for a single subject:
    1. Loads native CT and verified GI masks.
    2. Reorients both to canonical RAS+ for flawless medical rendering.
    3. Computes precise volumetric & HU attenuation metrics.
    4. Extracts 3D surface meshes (Marching Cubes).
    5. Saves standard .obj files for 3D Slicer / Blender / MeshLab.
    6. Saves standardized NIfTI masks in RAS+ space.
    7. Generates high-res 2D orthoview figure.
    8. Generates 8-slice anatomical progression montage.
    9. Generates 4-view 3D multi-angle static projection render.
    10. Generates standalone interactive 3D WebGL HTML viewer.
    11. Generates expert radiologist comparison if JHU ground truth exists.
    """
    print(f"\n=======================================================")
    print(f"Processing Showcase: {subject_id}")
    print(f"=======================================================")

    ct_path = os.path.join(data_dir, subject_id, "ct.nii.gz")
    if mask_dir:
        candidates = [
            os.path.join(mask_dir, f"{subject_id}_consensus.nii.gz"),
            os.path.join(mask_dir, f"{subject_id}_gi_seg.nii.gz"),
            os.path.join(mask_dir, f"{subject_id}_autolabel.nii.gz"),
            os.path.join(mask_dir, f"{subject_id}.nii.gz"),
        ]
        gi_path = next((p for p in candidates if os.path.exists(p)), None)
    else:
        gi_path = os.path.join(data_dir, subject_id, "gi_mask_temp.nii.gz")

    if not os.path.exists(ct_path) or not gi_path or not os.path.exists(gi_path):
        print(f"[ERROR] Missing CT or GI mask for {subject_id}")
        return None

    # Load CT and Mask in physical world space via SimpleITK
    ct_itk = sitk.ReadImage(ct_path)
    mask_itk = sitk.ReadImage(gi_path)

    # Resample mask directly onto the CT physical grid to guarantee exact spatial alignment
    is_exact_match = (
        mask_itk.GetSize() == ct_itk.GetSize()
        and np.allclose(mask_itk.GetSpacing(), ct_itk.GetSpacing(), atol=1e-3)
        and np.allclose(mask_itk.GetOrigin(), ct_itk.GetOrigin(), atol=1e-2)
        and np.allclose(mask_itk.GetDirection(), ct_itk.GetDirection(), atol=1e-2)
    )
    if is_exact_match:
        res_mask = mask_itk
    else:
        resampler = sitk.ResampleImageFilter()
        resampler.SetReferenceImage(ct_itk)
        resampler.SetInterpolator(sitk.sitkNearestNeighbor)
        resampler.SetDefaultPixelValue(0)
        res_mask = resampler.Execute(mask_itk)

    mask_arr = sitk.GetArrayFromImage(res_mask).transpose(2, 1, 0).astype(np.uint8)
    ct_arr = sitk.GetArrayFromImage(ct_itk).transpose(2, 1, 0).astype(np.float32)

    # Remap TotalSegmentator v2 IDs if present (6: stom, 19: duod, 18: small bowel, 20: colon)
    if np.any(np.isin(mask_arr, [6, 18, 19, 20])):
        ts_remap = np.zeros_like(mask_arr, dtype=np.uint8)
        ts_remap[mask_arr == 6] = 1
        ts_remap[mask_arr == 19] = 2
        ts_remap[mask_arr == 18] = 3
        ts_remap[mask_arr == 20] = 4
        mask_arr = ts_remap
        res_mask = sitk.GetImageFromArray(mask_arr.transpose(2, 1, 0))
        res_mask.CopyInformation(ct_itk)

    voxel_zooms = ct_itk.GetSpacing()
    voxel_volume_cm3 = np.prod(voxel_zooms) / 1000.0  # mm³ -> cm³ (mL)

    print(f"Canonical RAS+ Shape: {ct_arr.shape}, Voxel Spacing: {voxel_zooms}")

    # 1. Volumetric & HU Metrics
    metrics = {}
    subject_rows = []

    for oid, cfg in ORGAN_CONFIG.items():
        organ_voxels = (mask_arr == oid)
        v_count = int(np.sum(organ_voxels))
        v_cm3 = float(v_count * voxel_volume_cm3)

        if v_count > 0:
            organ_hu = ct_arr[organ_voxels]
            mean_hu = float(np.mean(organ_hu))
            std_hu = float(np.std(organ_hu))
            median_hu = float(np.median(organ_hu))
            coords = np.argwhere(organ_voxels)
            z_span = float((coords[:, 2].max() - coords[:, 2].min()) * voxel_zooms[2])
            y_span = float((coords[:, 1].max() - coords[:, 1].min()) * voxel_zooms[1])
            x_span = float((coords[:, 0].max() - coords[:, 0].min()) * voxel_zooms[0])
        else:
            mean_hu, std_hu, median_hu = 0.0, 0.0, 0.0
            x_span, y_span, z_span = 0.0, 0.0, 0.0

        metrics[oid] = {
            'organ_name': cfg['name'],
            'voxel_count': v_count,
            'volume_cm3': v_cm3,
            'mean_hu': mean_hu,
            'std_hu': std_hu,
            'median_hu': median_hu,
            'span_x_mm': x_span,
            'span_y_mm': y_span,
            'span_z_mm': z_span
        }

        subject_rows.append({
            'subject_id': subject_id,
            'organ_id': oid,
            'organ_name': cfg['name'],
            'voxel_count': v_count,
            'volume_cm3': round(v_cm3, 2),
            'mean_hu': round(mean_hu, 1),
            'std_hu': round(std_hu, 1),
            'median_hu': round(median_hu, 1),
            'span_x_mm': round(x_span, 1),
            'span_y_mm': round(y_span, 1),
            'span_z_mm': round(z_span, 1)
        })

    # 2. Extract 3D Surface Meshes via Marching Cubes
    mesh_dir = os.path.join(out_base_dir, "3d_meshes", subject_id)
    organ_meshes = {}

    for oid, cfg in ORGAN_CONFIG.items():
        binary_mask = (mask_arr == oid)
        if np.sum(binary_mask) < 200:
            organ_meshes[oid] = None
            continue

        smoothed = ndi.gaussian_filter(binary_mask.astype(np.float32), sigma=0.8)
        try:
            verts, faces, normals, values = measure.marching_cubes(
                smoothed, level=0.4, spacing=voxel_zooms, step_size=1
            )
            organ_meshes[oid] = {
                'verts': verts,
                'faces': faces,
                'normals': normals
            }
            obj_path = os.path.join(mesh_dir, f"{cfg['name'].lower().replace(' ', '_')}.obj")
            save_obj_mesh(verts, faces, obj_path, organ_name=cfg['name'])
        except Exception as e:
            print(f"[WARNING] Marching cubes failed for {cfg['name']}: {e}")
            organ_meshes[oid] = None

    combined_obj_path = os.path.join(mesh_dir, "all_gi_organs.obj")
    combined_verts = []
    combined_faces = []
    v_offset = 0
    for oid in [1, 2, 3, 4]:
        m = organ_meshes.get(oid)
        if m is not None:
            combined_verts.append(m['verts'])
            combined_faces.append(m['faces'] + v_offset)
            v_offset += len(m['verts'])
    if combined_verts:
        combined_verts = np.vstack(combined_verts)
        combined_faces = np.vstack(combined_faces)
        save_obj_mesh(combined_verts, combined_faces, combined_obj_path, organ_name=f"{subject_id}_all_gi")
        print(f"Saved canonical 3D OBJ to {combined_obj_path}")

    # 3. Standardized NIfTI Mask Export (Strictly aligned to CT physical grid)
    nifti_dir = os.path.join(out_base_dir, "nifti_masks")
    os.makedirs(nifti_dir, exist_ok=True)
    out_nii_path = os.path.join(nifti_dir, f"{subject_id}_gi_multiclass.nii.gz")
    sitk.WriteImage(res_mask, out_nii_path)
    print(f"Saved standardized NIfTI mask (matching CT grid) to {out_nii_path}")

    # 4. Generate Visualizations
    vis_dir = os.path.join(out_base_dir, "visualizations")
    ortho_path = os.path.join(vis_dir, f"{subject_id}_orthoview.png")
    montage_path = os.path.join(vis_dir, f"{subject_id}_montage.png")
    renders_3d_path = os.path.join(vis_dir, f"{subject_id}_3d_renders.png")

    render_orthoview_figure(ct_arr, mask_arr, voxel_zooms, ortho_path, subject_id, metrics)
    render_progression_montage(ct_arr, mask_arr, montage_path, subject_id)
    render_3d_multiangle(organ_meshes, renders_3d_path, subject_id, metrics)

    # 5. Interactive 3D WebGL HTML Viewer
    html_dir = os.path.join(out_base_dir, "interactive_3d")
    html_path = os.path.join(html_dir, f"{subject_id}_3d_interactive.html")
    generate_interactive_3d_html(organ_meshes, html_path, subject_id, metrics)

    # 6. Radiologist Ground Truth Comparison (if available)
    jhu_nrrd_file = os.path.join(jhu_dir, f"{subject_id}.seg.nrrd")
    if os.path.exists(jhu_nrrd_file):
        comp_path = os.path.join(vis_dir, f"{subject_id}_radiologist_gt_comparison.png")
        render_radiologist_comparison(ct_arr, mask_arr, jhu_nrrd_file, comp_path, subject_id, ct_path=ct_path, mask_path=gi_path)

    return subject_rows


